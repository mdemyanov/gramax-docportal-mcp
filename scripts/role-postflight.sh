#!/usr/bin/env bash
# role-postflight.sh [файл-теста…] — самопроверка роли ОДНИМ вызовом, сводкой, а не тремя выводами.
#
# ЗАЧЕМ (план волны NA-EPIC-52 Т4). Последний шаг роли — три прогона подряд (`check.sh --fast`,
# `validate-content`, точечные тесты), и каждый возвращал в контекст полный вывод; замер §1.2
# спутника ADR-102: 53 вызова `pytest`/`check.sh` за 2,3 волны по правилу исполняемой позиции.
# Здесь шаги идут ЗА ОДИН вызов, а вывод каждого уходит в файл через `run-quiet.sh`.
#
# ПОЧЕМУ ШАГИ НЕ ОБРЫВАЮТСЯ НА ПЕРВОМ КРАСНОМ. Роль, узнавшая только о первом падении, идёт
# гонять остальное руками — то есть возвращает в контекст ровно то, что вынесено. Поэтому
# исполняются ВСЕ шаги, а сводка называет исход каждого поимённо.
#
# ПРОГОН ТЕСТОВ НАЗЫВАЕТ ФАЙЛЫ. Аргументов нет — шаг тестов не исполняется вовсе и это
# сказано: сбор по каталогу внутри роли запрещён ресурсной дисциплиной (ADR-102 Д3, §8.6
# спутника), и обёртка не имеет права его обойти.
#
# ЧЕТВЁРТЫЙ ШАГ — ОКРЕСТНОСТЬ ПРЕДМЕТА (ADR-107 Д4). Именованные тесты роли и окрестность
# предмета — РАЗНЫЕ множества, и второе не заменяет первого: роль называет то, что писала, а
# окрестность собирается объявлениями `Governs:` тестов предмета. Код шага входит в свёртку
# `rc` наравне с тремя существующими. Предмет задачи прибор выводит из файлов сам; когда среди
# них нет ни требования, ни ADR (а обязанность сработала), роль называет предмет переменной
# NAUTA_TASK_SUBJECT='capability=<slug> adr=ADR-NNN' — шаг разворачивает её в аргументы прибора.
# У самого прибора переменной предмета НЕТ: она меняла бы исход прямого замера молча.
#
# Usage: bash scripts/role-postflight.sh [tests/test_x.py tests/test_y.py::test_z …]
set -u

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 2
QUIET="$REPO/scripts/run-quiet.sh"
[ -f "$QUIET" ] || { echo "ОШИБКА: нет $QUIET — сводке не через что идти" >&2; exit 2; }
# 17 строк на шаг: четыре шага плюс заголовок и вердикт укладываются в 73 строки — предел
# сводки постфлайта в контексте роли (план Т2 «≤ 20 строк» на носитель, четыре носителя плюс
# рамка).
export NAUTA_QUIET_MAX_LINES="${NAUTA_QUIET_MAX_LINES:-17}"

printf '===== ПОСТФЛАЙТ РОЛИ (%s) =====\n' "$REPO"

printf '[1/4] check.sh --fast\n'
bash "$QUIET" bash "$REPO/scripts/check.sh" --fast
rc_check=$?

printf '[2/4] validate-content.py\n'
bash "$QUIET" uv run "$REPO/scripts/validate-content.py"
rc_content=$?

if [ "$#" -eq 0 ]; then
  printf '[3/4] тесты НЕ названы — шаг не исполнен (сбор по каталогу внутри роли запрещён)\n'
  rc_tests=0
else
  printf '[3/4] pytest %s\n' "$*"
  bash "$QUIET" uv run --with pytest pytest "$@" -q
  rc_tests=$?
fi

printf '[4/4] окрестность предмета\n'
HOOD="$REPO/scripts/subject-neighbourhood.py"
if [ ! -f "$HOOD" ]; then
  # Громкий ноль, а не тихий проход: у дерева, получившего постфлайт без прибора, причина
  # названа (ADR-107 Д7, ADR-007 Д1) — прибор этой волной потребителю не доставляется.
  printf 'окрестность: прибора scripts/subject-neighbourhood.py в этом дереве нет — шаг не исполнен\n'
  rc_neighbourhood=0
else
  # Среду в АРГУМЕНТ разворачивает зовущий: у прибора переменной предмета нет, иначе она меняла
  # бы исход прямого замера молча. Пусто — предмет выводится из файлов предмета самим прибором.
  hood_subject=""
  for s in ${NAUTA_TASK_SUBJECT:-}; do hood_subject="$hood_subject --subject $s"; done
  # shellcheck disable=SC2086 — разбиение на слова здесь предмет, а не оплошность
  bash "$QUIET" uv run "$HOOD" --run $hood_subject
  rc_neighbourhood=$?
fi

rc=0
for r in "$rc_check" "$rc_content" "$rc_tests" "$rc_neighbourhood"; do [ "$r" -ne 0 ] && rc=1; done
printf 'постфлайт: rc=%s — check.sh=%s validate-content=%s pytest=%s окрестность=%s\n' \
  "$rc" "$rc_check" "$rc_content" "$rc_tests" "$rc_neighbourhood"
exit "$rc"
