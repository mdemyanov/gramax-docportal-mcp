#!/usr/bin/env bash
# run-quiet.sh — длинный вывод уходит в файл, в контекст возвращаются rc, сводка и путь.
#
# ЗАЧЕМ (ADR-102, план волны NA-EPIC-52 Т2; §5 спутника, строка компонента). Результат
# инструмента оплачивается КАЖДЫМ последующим обращением сессии: замер §1.1 спутника —
# результаты Bash вернули в контекст 801 220 байт за одну волну, и верхние двадцать вызовов
# дали 38 % расхода. Обёртка снимает эту цену: полный вывод живёт в файле, в контексте
# остаются rc, путь и сводка не длиннее NAUTA_QUIET_MAX_LINES строк.
#
# ПОЧЕМУ СВОДКА НАЗЫВАЕТ ПАДЕНИЯ ПОИМЁННО. Сводка, несущая только «упало», побеждает
# механизм, которому принадлежит: агент идёт читать файл обратно ЦЕЛИКОМ, и результат снова
# в контексте — до конца сессии. Поэтому на красном исходе печатаются распознанные красные
# строки, а если ни одна не распознана — хвост файла, но никогда голое «упало».
#
# ЧЕГО ОБЁРТКА НЕ ДЕЛАЕТ (граница §5 спутника дословно): «не решает, что запускать — она
# оборачивает то, что ей дали». Аргументы, кавычки и код возврата доходят до обёрнутой
# команды и обратно неизменёнными; своего вердикта у обёртки нет.
#
# Usage: bash scripts/run-quiet.sh <команда> [аргументы…]
#   NAUTA_QUIET_DIR       — каталог файлов полного вывода (по умолчанию $TMPDIR)
#   NAUTA_QUIET_MAX_LINES — предел сводки в строках (по умолчанию 20, план Т2)
set -u

MAX_LINES="${NAUTA_QUIET_MAX_LINES:-20}"
OUT_DIR="${NAUTA_QUIET_DIR:-${TMPDIR:-/tmp}}"

if [ "$#" -lt 1 ]; then
  echo "ОШИБКА: run-quiet.sh обёртывает команду, а команда не названа." >&2
  echo "  Usage: bash scripts/run-quiet.sh <команда> [аргументы…]" >&2
  exit 2
fi

mkdir -p "$OUT_DIR" 2>/dev/null || true
log="$(mktemp "${OUT_DIR%/}/run-quiet-XXXXXX")" || {
  echo "ОШИБКА: не создан файл полного вывода в ${OUT_DIR%/} — обёртка НЕ выносит вывод" >&2
  exit 2
}

# Красные строки — объявленный перечень написаний, а не «всё, где встречается error»:
# распознаватель, ловящий подстроку, назвал бы красной строку `0 errors` зелёного прогона.
RED_RE='^(FAILED|ERROR|FAIL|ОШИБКА|ОТКАЗ|not ok|✗|✖|✘)|^E {3}|^[[:space:]]*(ОШИБКА|ERROR):|^-+ FAIL|^=+ .*(failed|error)'

"$@" >"$log" 2>&1
rc=$?

total="$(wc -l <"$log" | tr -d ' ')"
head_room=$(( MAX_LINES - 2 ))
[ "$head_room" -lt 1 ] && head_room=1

{
  printf 'run-quiet: rc=%s | строк полного вывода: %s | полный вывод: %s\n' "$rc" "$total" "$log"
  if [ "$rc" -ne 0 ]; then
    red="$(grep -a -E "$RED_RE" "$log" 2>/dev/null | head -n "$head_room")"
    if [ -n "$red" ]; then
      red_total="$(grep -a -c -E "$RED_RE" "$log" 2>/dev/null || echo 0)"
      printf 'красных строк: %s, показано не больше %s:\n' "$red_total" "$head_room"
      printf '%s\n' "$red"
    else
      printf 'красных строк не распознано; хвост полного вывода:\n'
      tail -n "$head_room" "$log"
    fi
  fi
} 2>/dev/null | head -n "$MAX_LINES"

exit "$rc"
